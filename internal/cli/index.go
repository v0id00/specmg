package cli

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/spf13/cobra"
	"github.com/v0id00/specmg/internal/output"
	"github.com/v0id00/specmg/internal/store"
)

var indexWrite bool

var indexCmd = &cobra.Command{
	Use:   "index",
	Short: "Print (or --write) specs/INDEX.md — a table of all specs",
	RunE: func(cmd *cobra.Command, args []string) error {
		root, err := resolveRoot()
		if err != nil {
			return err
		}
		all, err := store.List(root, flagDir)
		if err != nil {
			return err
		}
		var b strings.Builder
		b.WriteString("# Spec Index\n\n<!-- generated by specmg index; do not edit by hand -->\n\n")
		b.WriteString("| ID | Status | Title | Owner | Tags |\n|----|--------|-------|-------|------|\n")
		for _, s := range all {
			fmt.Fprintf(&b, "| [%s](%s) | %s | %s | %s | %s |\n",
				s.FM.ID, s.Filename(), s.FM.Status, s.FM.Title, s.FM.Owner, strings.Join(s.FM.Tags, ", "))
		}
		if flagJSON {
			type idxRow struct {
				ID, Status, Title, Owner string
				Tags                     []string
			}
			var rows []idxRow
			for _, s := range all {
				rows = append(rows, idxRow{s.FM.ID, s.FM.Status, s.FM.Title, s.FM.Owner, s.FM.Tags})
			}
			return output.JSON(cmd.OutOrStdout(), rows)
		}
		if !indexWrite {
			fmt.Fprint(cmd.OutOrStdout(), b.String())
			return nil
		}
		path := filepath.Join(root, flagDir, "INDEX.md")
		if flagDryRun {
			fmt.Fprintf(cmd.OutOrStdout(), "would write %s (%d specs)\n", path, len(all))
			return nil
		}
		if err := os.WriteFile(path, []byte(b.String()), 0o644); err != nil {
			return err
		}
		fmt.Fprintf(cmd.OutOrStdout(), "wrote %s (%d specs)\n", path, len(all))
		return nil
	},
}

func init() {
	indexCmd.Flags().BoolVar(&indexWrite, "write", false, "write specs/INDEX.md instead of printing")
	rootCmd.AddCommand(indexCmd)
}
